// Regenerate TO-DOS.md from the Trello board, which is canonical since S191.
// Run at every handover, from the repo root:   node scripts/trello-snapshot.mjs
//
// Keeps the file's header, each section's heading + intro line, and the housekeeping
// notes at the foot verbatim; only the tables are rebuilt. Card label = section,
// card position on the board = row order. Read-only against Trello.
import fs from 'node:fs';

const env = Object.fromEntries(fs.readFileSync('trello.env', 'utf8').split(/\r?\n/)
  .filter(l => l.includes('=')).map(l => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]));
const BOARD = '6ab38135b3aee497becc9753';
const get = async path => {
  const r = await fetch(`https://api.trello.com/1/${path}${path.includes('?') ? '&' : '?'}key=${env.TRELLO_KEY}&token=${env.TRELLO_TOKEN}`);
  if (!r.ok) throw new Error(`${path}: ${r.status} ${await r.text()}`);
  return r.json();
};

const SECTIONS = [['## 1', 'F&F trial'], ['## 2', 'Before launch'], ['## 3', 'Launch day'], ['## 4', 'After launch'], ['## 5', 'Someday']];
const OPEN_ORDER = ['In progress', 'Blocked', 'Next up', 'Backlog'];

const [lists, labels, cards] = await Promise.all([
  get(`boards/${BOARD}/lists`), get(`boards/${BOARD}/labels`),
  get(`boards/${BOARD}/cards?fields=name,desc,idList,idLabels,pos`),
]);
const listName = Object.fromEntries(lists.map(l => [l.id, l.name]));
const labelName = Object.fromEntries(labels.map(l => [l.id, l.name]));

// Imported cards carry "item\n\nnotes\n\n— TO-DOS #N"; newer ones are free text. Either way
// the table gets one line: the notes, or the first paragraph.
function note(card) {
  const paras = card.desc.split(/\n\s*\n/).map(p => p.trim()).filter(p => p && !/^— (TO-DOS|moved from)/.test(p));
  const body = /^— TO-DOS #/m.test(card.desc) && paras.length > 1 ? paras[1] : paras[0] || '';
  return body.replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|');
}
const row = c => {
  const status = listName[c.idList];
  const tag = status === 'Backlog' ? '' : `**[${status}]** `;
  const [, num, title] = c.name.match(/^#(\d+) · (.*)$/) || [, '?', c.name];
  return `| ${num} | ${title.replace(/\|/g, '\\|')} | ${tag}${note(c)} |`;
};
const byBoardOrder = (a, b) => OPEN_ORDER.indexOf(listName[a.idList]) - OPEN_ORDER.indexOf(listName[b.idList]) || a.pos - b.pos;

const raw = fs.readFileSync('TO-DOS.md', 'utf8');
const nl = raw.includes('\r\n') ? '\r\n' : '\n';   // keep the file's own line endings
const src = raw.replace(/\r\n/g, '\n');
// The header ends at a fixed line, so re-running never stacks a second snapshot notice.
const HEADER_END = 'Do not renumber.';
const header = src.slice(0, src.indexOf(HEADER_END) + HEADER_END.length);
const foot = src.slice(src.indexOf('## Housekeeping'));
const open = cards.filter(c => OPEN_ORDER.includes(listName[c.idList]));

let out = header +
  `\n> _Snapshot of the Trello board (canonical since S191): https://trello.com/b/HCrNJRN1/aevia.\n` +
  `> Regenerated by \`node scripts/trello-snapshot.mjs\` at handover. Edit the board, not this file._\n\n---\n\n`;
for (const [prefix, label] of SECTIONS) {
  const head = src.slice(src.indexOf(prefix)).split('\n').slice(0, 2).join('\n');
  const rows = open.filter(c => c.idLabels.some(id => labelName[id] === label)).sort(byBoardOrder).map(row);
  out += `${head}\n\n| # | Item | Notes |\n|---|------|-------|\n${rows.join('\n')}\n\n---\n\n`;
}
const unlabelled = open.filter(c => !c.idLabels.some(id => SECTIONS.some(([, l]) => l === labelName[id])));
if (unlabelled.length) out += `## ⚠ Unlabelled on the board\n\n${unlabelled.map(c => `- ${c.name}`).join('\n')}\n\n---\n\n`;
const closed = cards.filter(c => ['Done', 'Dropped'].includes(listName[c.idList]));
out += `## Closed on the board (not yet archived)\n\n${closed.map(c => `- **${listName[c.idList]}** — ${c.name}`).join('\n') || '_none_'}\n\n---\n\n`;
out += foot;

fs.writeFileSync('TO-DOS.md', out.replace(/\n/g, nl));
console.log(`TO-DOS.md: ${open.length} open, ${closed.length} closed${unlabelled.length ? `, ⚠ ${unlabelled.length} unlabelled` : ''}`);
